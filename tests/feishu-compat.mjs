import assert from 'node:assert/strict';
import { mkdtemp, writeFile, readFile, rm, mkdir } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { transform } from '../skill/modes/04-feishu/scripts/html-to-docxxml.mjs';
import { prepareMedia } from '../skill/modes/04-feishu/scripts/upload-media.mjs';
import { normalizeNativeXml } from '../skill/modes/04-feishu/scripts/native-xml.mjs';
import { prepareHtmlBlock } from '../skill/modes/04-feishu/scripts/html-block.mjs';
import { splitDocxXML } from '../skill/modes/04-feishu/scripts/chunk-doc.mjs';
import { appendToDoc, replaceSection, replaceByText, deleteByText } from '../skill/modes/04-feishu/scripts/update-doc.mjs';
import { createDoc } from '../skill/modes/04-feishu/scripts/create-doc.mjs';
const dir = await mkdtemp(join(tmpdir(), 'h2w-feishu-test-'));
const savedBin = process.env.LARK_CLI_BIN;
try {
  const chrome = transform('<header>不应保留导航<a>导航链接</a><button>删除按钮</button></header><main><p>正文</p></main>', {boundaryAnnotations:{button:{type:'drop'}}});
  assert.doesNotMatch(chrome.docxxml,/导航链接/);
  assert.match(chrome.docxxml,/正文/);
  const rescued = transform('<aside><div class="quote"><p>应保留的提示内容</p></div></aside>', {boundaryAnnotations:{'.quote':{type:'callout'}}});
  assert.match(rescued.docxxml,/应保留的提示内容/);
  const png = 'iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jL1sAAAAASUVORK5CYII=';
  const r = transform(`<main><article><p>一章</p></article><article><p>二章</p></article><img src="data:image/png;base64,${png}" width="1" height="1" alt='图 &quot;A&quot; &amp; B'><p>尾部</p></main>`);
  assert.match(r.docxxml,/一章/); assert.match(r.docxxml,/二章/);
  const m = await prepareMedia(r.docxxml,r.mediaTasks,{resourceDir:join(dir,'assets'),cwd:dir});
  assert.match(m.docxxml,/<img path="@\.\/assets\/image-001.png"/);
  assert.ok(m.docxxml.indexOf('<img') < m.docxxml.indexOf('尾部'));
  assert.equal(m.docxxml.includes('IMG_PLACEHOLDER'), false);
  assert.equal((await readFile(m.files[0])).length,Buffer.from(png,'base64').length);
  const normalized = normalizeNativeXml('<title>测试</title><callout><h2>标题</h2><p>之前</p><img path="@./a.png"/><p>之后</p></callout>');
  assert.match(normalized.docxxml,/<p><b>标题<\/b><\/p>/);
  assert.match(normalized.docxxml,/<\/callout><img[^>]+\/><callout>/);
  assert.match(normalized.docxxml,/之后/);
  assert.equal(normalized.warnings.length,2);
  await mkdir(join(dir,'input'));
  await writeFile(join(dir,'outside.png'),Buffer.from(png,'base64'));
  const outside=transform('<img src="../outside.png">');
  await assert.rejects(prepareMedia(outside.docxxml,outside.mediaTasks,{resourceDir:join(dir,'assets'),cwd:dir,inputDir:join(dir,'input')}),/越出输入目录/);
  const x = '<title>标题</title>'+Array.from({length:10},()=>'<p>'+ '中'.repeat(10)+'</p>').join('');
  const chunks = splitDocxXML(x,100);
  assert.equal(chunks.join(''),x);
  assert.ok(chunks.every(c=>Buffer.byteLength(c)<=100));
  const h = await prepareHtmlBlock('<!doctype html><html><head><title>测试</title></head><body><p>完整 HTML</p></body></html>',{resourceDir:join(dir,'html'),title:'测试'});
  assert.match(h.docxxml,/html5-block/);
  assert.match(await readFile(h.files[0],'utf8'),/html-box-height-mode/);
  await assert.rejects(prepareHtmlBlock('<head></head><body><img src="./private.png"></body>',{resourceDir:dir}),/本地资源/);
  await assert.rejects(prepareHtmlBlock('<head><style>body{background:url(./private.png)}</style></head><body></body>',{resourceDir:dir}),/本地资源/);
  await assert.rejects(prepareHtmlBlock('<head></head><body>'+ '中'.repeat(180000)+'</body>',{resourceDir:dir}),/500KB/);
  assert.throws(()=>replaceSection('test','## 标题','文字'),/block ID/);
  assert.throws(()=>replaceByText('test','开始...结尾','文字'),/跨块/);
  // Offline transport fixture checks v2 request construction and partial failures.
  const bin=join(dir,'cli.mjs');
  await writeFile(bin,`#!${process.execPath}\nlet data=''; for await (const c of process.stdin) data+=c; const args=process.argv.slice(2); console.log(JSON.stringify({ok:true, data:{args,input:data,document:{url:'https://example.com/test',document_id:'test',new_blocks:[]}}}));`,{mode:0o700});
  process.env.LARK_CLI_BIN=bin;
  let out=await appendToDoc('test','正文',{dryRun:true});
  assert.ok(out.raw.data.args.includes('--command')); assert.ok(!out.raw.data.args.includes('--mode'));
  assert.equal(out.raw.data.input,'正文');
  out=await replaceSection('test','## 标题','替换',{blockId:'fresh',dryRun:true}); assert.ok(out.raw.data.args.includes('fresh'));
  out=await deleteByText('test','文字',{blockId:'fresh',dryRun:true}); assert.ok(out.raw.data.args.includes('block_delete'));
  const created=await createDoc('<title>测试</title>',{dryRun:true}); assert.ok(created.raw.data.args.includes('--doc-format'));
  console.log('feishu local conversion/resources/v2 contract checks passed');
} finally {
  if(savedBin===undefined)delete process.env.LARK_CLI_BIN;else process.env.LARK_CLI_BIN=savedBin;
  await rm(dir,{recursive:true,force:true});
}
